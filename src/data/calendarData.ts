const generateDays = (days: number, cur: number): DayDatas[] => {
  return Array.from({ length: days }, (_, i) => {
    const dayNum = i + 1;
    const hasTrade = Math.random() > 0.35;
    const pnl = hasTrade ? Math.floor(Math.random() * 200) - 80 : undefined;
    const trades = hasTrade ? Math.floor(Math.random() * 8) + 1 : undefined;

    return {
      d: dayNum,
      m: cur,
      p: pnl,
      t: trades,
    };
  });
};

